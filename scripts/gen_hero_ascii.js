/**
 * scripts/gen_hero_ascii.js
 * Ledgio Build-time Hero ASCII Sampler (Phase A5)
 *
 * Samples docs/ui/v2/refs/hero-art.webp into monospace grid cells (~11x14 px),
 * extracts glowing step tops, lit edges, and the upper-right pixel cluster,
 * discarding the dark void and diffuse smoke.
 *
 * Outputs: assets/js/hero-ascii-v1.js
 * Budget: <= 3,500 cells, file size <= 40KB.
 */

const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const repoRoot = path.resolve(__dirname, '..');
const srcImage = path.join(repoRoot, 'docs', 'ui', 'v2', 'refs', 'hero-art.webp');
const outJs = path.join(repoRoot, 'assets', 'js', 'hero-ascii-v1.js');

if (!fs.existsSync(srcImage)) {
  console.error(`Error: source image not found at ${srcImage}`);
  process.exit(1);
}

// Python helper script to decode WebP and sample cell luminance & colors
const pyScript = `
import sys, json
from PIL import Image

src = sys.argv[1]
im = Image.open(src).convert('RGB')
w, h = im.size
pixels = im.load()

cell_w = 11
cell_h = 14
cols = w // cell_w
rows = h // cell_h

cells = []

# Character ramp: · : + 0 1 $ ₹
# Indices:
# 0: ·
# 1: :
# 2: +
# 3: 0
# 4: 1
# 5: $
# 6: ₹

for r in range(rows):
    for c in range(cols):
        x0 = c * cell_w
        y0 = r * cell_h

        r_sum = 0
        g_sum = 0
        b_sum = 0
        count = cell_w * cell_h

        for y in range(y0, y0 + cell_h):
            for x in range(x0, x0 + cell_w):
                pr, pg, pb = pixels[x, y]
                r_sum += pr
                g_sum += pg
                b_sum += pb

        avg_r = r_sum / count
        avg_g = g_sum / count
        avg_b = b_sum / count
        lum = 0.2126 * avg_r + 0.7152 * avg_g + 0.0722 * avg_b

        x_pct = (x0 + cell_w / 2.0) / w
        y_pct = (y0 + cell_h / 2.0) / h

        # Skip smoke in bottom-right (diffuse low-contrast haze)
        is_smoke = (x_pct > 0.72 and y_pct > 0.62 and lum < 75)
        # Skip dark void on left
        is_left_void = (x_pct < 0.20 and y_pct < 0.70)

        is_lit = False
        if not is_smoke and not is_left_void:
            if lum >= 22.0:
                is_lit = True
            elif lum >= 14.0 and (avg_g > avg_r * 1.3 or avg_b > avg_r * 1.3):
                # Subtle lit edge
                is_lit = True

        if is_lit:
            # Determine brightness level (1..4) and character index (0..6)
            if lum >= 110.0:
                bright = 4
                char_idx = 6 if lum >= 165.0 else 5 # ₹ or $
            elif lum >= 65.0:
                bright = 3
                char_idx = 4 if lum >= 85.0 else 3  # 1 or 0
            elif lum >= 38.0:
                bright = 2
                char_idx = 2 if lum >= 50.0 else 1  # + or :
            else:
                bright = 1
                char_idx = 1 if lum >= 28.0 else 0  # : or ·

            cells.append([
                round(x_pct * 100.0, 2),
                round(y_pct * 100.0, 2),
                bright,
                char_idx
            ])

print(json.dumps(cells))
`;

console.log(`Sampling ${srcImage}...`);
const resultJson = execFileSync('python', ['-c', pyScript, srcImage], {
  encoding: 'utf-8',
  maxBuffer: 20 * 1024 * 1024
});

const cells = JSON.parse(resultJson);
const count = cells.length;
console.log(`Sampled ${count} ASCII cells.`);

// Unpack into parallel typed arrays for maximum runtime performance & compact serialization
const xs = cells.map(c => c[0]);
const ys = cells.map(c => c[1]);
const bs = cells.map(c => c[2]);
const cs = cells.map(c => c[3]);

const banner = `/**
 * Ledgio Hero ASCII Data (v1)
 * Auto-generated by scripts/gen_hero_ascii.js — DO NOT EDIT DIRECTLY.
 * Source: docs/ui/v2/refs/hero-art.webp
 * Cells: ${count}
 */
(function(window) {
  'use strict';
  var CHARS = ['·', ':', '+', '0', '1', '$', '₹'];
  var X = ${JSON.stringify(xs)};
  var Y = ${JSON.stringify(ys)};
  var B = ${JSON.stringify(bs)};
  var C = ${JSON.stringify(cs)};

  window.__LEDGIO_HERO_ASCII = {
    chars: CHARS,
    count: ${count},
    x: X,
    y: Y,
    b: B,
    c: C,
    get: function(i) {
      return { x: X[i], y: Y[i], b: B[i], c: C[i], char: CHARS[C[i]] };
    }
  };
  Object.defineProperty(window.__LEDGIO_HERO_ASCII, 'cells', {
    get: function() {
      if (!this._cachedCells) {
        var arr = new Array(this.count);
        for (var i = 0; i < this.count; i++) {
          arr[i] = [X[i], Y[i], B[i], C[i]];
        }
        this._cachedCells = arr;
      }
      return this._cachedCells;
    }
  });
})(typeof window !== 'undefined' ? window : globalThis);
`;

fs.writeFileSync(outJs, banner, 'utf-8');
const fileStats = fs.statSync(outJs);
const fileSizeKb = (fileStats.size / 1024).toFixed(2);

console.log(`Generated ${outJs}`);
console.log(`File size: ${fileSizeKb} KB (${fileStats.size} bytes)`);

// Self-check validation
const MAX_CELLS = 3500;
const MIN_CELLS = 500;
const MAX_BYTES = 40 * 1024; // 40KB budget

if (count < MIN_CELLS || count > MAX_CELLS) {
  console.error(`SELF-CHECK FAILED: cell count ${count} is outside permitted range [${MIN_CELLS}, ${MAX_CELLS}]!`);
  process.exit(1);
}

if (fileStats.size > MAX_BYTES) {
  console.error(`SELF-CHECK FAILED: file size ${fileStats.size} bytes (${fileSizeKb} KB) exceeds maximum 40KB budget (${MAX_BYTES} bytes)!`);
  process.exit(1);
}

console.log(`✓ SELF-CHECK PASSED: ${count} cells (<= ${MAX_CELLS}), ${fileSizeKb} KB (<= 40 KB).`);
